"""Derived numbers for the README (relative gains, daily spread, CV-vs-test gap).

Reads reports/final_results.json and reports/cv_results.csv only; touches no raw data.
Writes reports/summary.md.
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

import pandas as pd

from taxi import config

NL = chr(10)
fin = json.loads((config.REPORTS_DIR / "final_results.json").read_text())
cv = pd.read_csv(config.REPORTS_DIR / "cv_results.csv").set_index("model")
res = pd.DataFrame(fin["results"]).set_index("model")
final = res.index[res.index.str.startswith("FINAL")][0]
daily = pd.DataFrame(fin["daily"])

lines = ["# Derived numbers (generated by scripts/summary.py)", ""]
for ref in ["global median", "route-hour median (same sample)", "route-hour median (all training-month trips)"] + [i for i in res.index if i.startswith("best Ridge")]:
    mae = 1 - res.loc[final, "mae_min"] / res.loc[ref, "mae_min"]
    rmse = 1 - res.loc[final, "rmse_min"] / res.loc[ref, "rmse_min"]
    lines.append(f"- Test MAE of the final model is {mae:.1%} lower and RMSE {rmse:.1%} lower than `{ref}`.")
cvrow = cv.loc[fin["final_model"]]
lines.append(f"- CV (training month) MAE {cvrow.mae_min_mean:.3f} +/- {cvrow.mae_min_std:.3f}, RMSE {cvrow.rmse_min_mean:.3f} +/- {cvrow.rmse_min_std:.3f}; "
             f"held-out month MAE {res.loc[final, 'mae_min']:.3f}, RMSE {res.loc[final, 'rmse_min']:.3f} "
             f"(MAE {res.loc[final, 'mae_min'] / cvrow.mae_min_mean - 1:+.1%} vs CV mean).")
wins = int((daily.final_mae < daily.baseline_mae).sum())
lines.append(f"- The final model beats the same-sample route-hour baseline on {wins} of {len(daily)} test days; daily MAE of the final model: "
             f"mean {daily.final_mae.mean():.2f}, std {daily.final_mae.std():.2f}, min {daily.final_mae.min():.2f}, max {daily.final_mae.max():.2f} min.")
h, o = daily[daily.holiday], daily[~daily.holiday]
for r in h.itertuples():
    lines.append(f"- Holiday {r.day} ({r.dow}): final MAE {r.final_mae:.2f} vs baseline {r.baseline_mae:.2f} "
                 f"({1 - r.final_mae / r.baseline_mae:.1%} gain); on non-holiday days the average gain is "
                 f"{(1 - o.final_mae / o.baseline_mae).mean():.1%}. Mean duration that day {r.mean_duration:.2f} min vs {o.mean_duration.mean():.2f} on other days.")
wk = daily[daily.dow.isin(["Saturday", "Sunday"])]
lines.append(f"- Weekend-day mean MAE {wk.final_mae.mean():.2f} vs weekday {daily[~daily.dow.isin(['Saturday', 'Sunday'])].final_mae.mean():.2f} min.")
(config.REPORTS_DIR / "summary.md").write_text(NL.join(lines) + NL, encoding="utf-8")
print(NL.join(lines))
